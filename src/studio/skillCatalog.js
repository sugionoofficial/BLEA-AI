/** Cari kategori & kemampuan berdasarkan kata kunci; dipakai pencarian Studio. */
export function searchSkillCatalog(query) {
  const needle = String(query || '').trim().toLowerCase();
  if (!needle) return [];
  const hits = [];
  for (const category of SKILL_CATALOG) {
    const categoryMatch = category.label.toLowerCase().includes(needle);
    for (const skill of category.skills) {
      if (categoryMatch || skill.toLowerCase().includes(needle)) {
        hits.push({ skill, category: category.label, categoryId: category.id, icon: category.icon });
      }
    }
  }
  return hits;
}

