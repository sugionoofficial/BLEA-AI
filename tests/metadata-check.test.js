const enc = new TextEncoder();

function concat(...arrays) {
  const total = arrays.reduce((sum, a) => sum + a.length, 0);
  const out = new Uint8Array(total);
  let off = 0;
  for (const a of arrays) {
    out.set(a, off);
    off += a.length;
  }
  return out;
}

function u32be(n) {
  return new Uint8Array([(n >>> 24) & 0xff, (n >>> 16) & 0xff, (n >>> 8) & 0xff, n & 0xff]);
}

function u32le(n) {
  return new Uint8Array([n & 0xff, (n >>> 8) & 0xff, (n >>> 16) & 0xff, (n >>> 24) & 0xff]);
}

function u16be(n) {
  return new Uint8Array([(n >>> 8) & 0xff, n & 0xff]);
}

function pngChunk(type, data = new Uint8Array(0)) {
  return concat(u32be(data.length), enc.encode(type), data, new Uint8Array(4));
}

function buildAiPng() {
  const sig = new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  const ihdr = pngChunk('IHDR', new Uint8Array([0, 0, 0, 1, 0, 0, 0, 1, 8, 2, 0, 0, 0]));
  const textParams = pngChunk('tEXt', enc.encode('parameters\0Astronaut portrait\nNegative prompt: blur\nSteps: 28, Sampler: Euler a, CFG scale: 7, Seed: 42'));
  const textWorkflow = pngChunk('tEXt', enc.encode('workflow\0{"3":{"class_type":"KSampler","inputs":{"seed":42}}}'));
  const cabx = pngChunk('caBX', enc.encode('c2pa.assertions OpenAI DALL-E'));
  const idat = pngChunk('IDAT', new Uint8Array([0x78, 0x9c, 0x63, 0x60, 0x00, 0x00, 0x00, 0x02, 0x00, 0x01]));
  const iend = pngChunk('IEND');
  return concat(sig, ihdr, textParams, textWorkflow, cabx, idat, iend);
}

function buildAiJpeg() {
  const soi = new Uint8Array([0xff, 0xd8]);
  const app0 = concat(new Uint8Array([0xff, 0xe0]), u16be(2 + 5), enc.encode('JFIF\0'));
  const xmpPayload = enc.encode('http://ns.adobe.com/xap/1.0/\0<x:xmpmeta><rdf:RDF><rdf:Description xmp:CreatorTool="OpenAI ChatGPT" iptcExt:DigitalSourceType="http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia"/></rdf:RDF></x:xmpmeta>');
  const app1Xmp = concat(new Uint8Array([0xff, 0xe1]), u16be(2 + xmpPayload.length), xmpPayload);
  const iccPayload = enc.encode('ICC_PROFILE\0test-icc');
  const app2Icc = concat(new Uint8Array([0xff, 0xe2]), u16be(2 + iccPayload.length), iccPayload);
  const c2paPayload = enc.encode('jumbc2pa Content Credentials');
  const app11 = concat(new Uint8Array([0xff, 0xeb]), u16be(2 + c2paPayload.length), c2paPayload);
  const comPayload = enc.encode('Generated by Midjourney --v 6.1 --stylize 100');
  const com = concat(new Uint8Array([0xff, 0xfe]), u16be(2 + comPayload.length), comPayload);
  const sos = new Uint8Array([0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00, 0xaa, 0xbb, 0xff, 0xd9]);
  return concat(soi, app0, app1Xmp, app2Icc, app11, com, sos);
}

function buildAiWebp() {
  const vp8xPayload = new Uint8Array(10);
  vp8xPayload[0] = 0x0c; // EXIF (0x08) + XMP (0x04)
  const vp8x = concat(enc.encode('VP8X'), u32le(10), vp8xPayload);
  const vp8 = concat(enc.encode('VP8 '), u32le(4), new Uint8Array([1, 2, 3, 4]));
  const xmpBytes = enc.encode('<x:xmpmeta><AIGC>{"AIGC":{"Label":"1","ContentProducer":"Alibaba Wan2.6"}}</AIGC></x:xmpmeta>');
  const xmpPad = xmpBytes.length % 2 ? new Uint8Array([0]) : new Uint8Array(0);
  const xmp = concat(enc.encode('XMP '), u32le(xmpBytes.length), xmpBytes, xmpPad);
  const body = concat(vp8x, vp8, xmp);
  return concat(enc.encode('RIFF'), u32le(4 + body.length), enc.encode('WEBP'), body);
}

function buildAiGif() {
  const header = concat(enc.encode('GIF89a'), new Uint8Array([1, 0, 1, 0, 0x00, 0, 0]));
  const netscapeBody = enc.encode('NETSCAPE2.0');
  const netscapeExt = concat(new Uint8Array([0x21, 0xff, netscapeBody.length]), netscapeBody, new Uint8Array([3, 1, 0, 0, 0]));
  const comBytes = enc.encode('Made with Runway Gen-3 Alpha');
  const comExt = concat(new Uint8Array([0x21, 0xfe, comBytes.length]), comBytes, new Uint8Array([0]));
  const imgBlock = new Uint8Array([0x2c, 0, 0, 0, 0, 1, 0, 1, 0, 0, 2, 2, 0x44, 0x01, 0]);
  return concat(header, netscapeExt, comExt, imgBlock, new Uint8Array([0x3b]));
}

function mp4Box(type, payload) {
  return concat(u32be(8 + payload.length), enc.encode(type), payload);
}

function buildAiMp4() {
  const ftyp = mp4Box('ftyp', enc.encode('isom\x00\x00\x02\x00isommp41'));
  const udtaData = mp4Box('data', concat(new Uint8Array(8), enc.encode('{"AIGC":{"Label":"1","ContentProducer":"com.openai.sora"}}')));
  const udtaItem = mp4Box('©too', udtaData);
  const ilst = mp4Box('ilst', udtaItem);
  const meta = mp4Box('meta', concat(new Uint8Array(4), ilst));
  const udta = mp4Box('udta', meta);
  const mvhd = mp4Box('mvhd', new Uint8Array(12));

  // Build stbl/stco pointing to mdat payload after moov!
  const customHdlr = mp4Box('hdlr', concat(new Uint8Array(8), enc.encode('vide'), new Uint8Array(12), enc.encode('OpenAI Sora Handler\0')));
  const stcoPlaceholder = mp4Box('stco', concat(new Uint8Array(4), u32be(1), u32be(0)));
  const stbl = mp4Box('stbl', stcoPlaceholder);
  const minf = mp4Box('minf', stbl);
  const mdia = mp4Box('mdia', concat(customHdlr, minf));
  const trak = mp4Box('trak', mdia);
  const moov = mp4Box('moov', concat(mvhd, udta, trak));
  const c2paUuid = mp4Box('uuid', concat(new Uint8Array([0xd8, 0xfe, 0xc3, 0xd6, 0x1b, 0x0e, 0x48, 0x3c, 0x92, 0x97, 0x58, 0x28, 0x87, 0x7e, 0xc4, 0x81]), enc.encode('c2pa-manifest')));
  const mdatPayload = enc.encode('VIDEO-DATA-PAYLOAD');
  const mdat = mp4Box('mdat', mdatPayload);

  const file = concat(ftyp, moov, c2paUuid, mdat);
  const mdatStart = ftyp.length + moov.length + c2paUuid.length;
  // Write real stco chunk offset pointing into mdatPayload (+8)
  const stcoMarker = enc.encode('stco');
  for (let i = 0; i <= file.length - 16; i += 1) {
    if (file[i] === stcoMarker[0] && file[i + 1] === stcoMarker[1] && file[i + 2] === stcoMarker[2] && file[i + 3] === stcoMarker[3]) {
      file.set(u32be(mdatStart + 8), i + 12);
      break;
    }
  }
  return { file, mdatPayloadOffsetBefore: mdatStart + 8 };
}

function buildAiWebm() {
  const ebmlHeader = new Uint8Array([0x1a, 0x45, 0xdf, 0xa3, 0x84, 0x42, 0x86, 0x81, 0x01]);
  const writeAppBytes = enc.encode('ComfyUI Video Exporter');
  const writingApp = concat(new Uint8Array([0x57, 0x41, 0x80 | writeAppBytes.length]), writeAppBytes);
  const info = concat(new Uint8Array([0x15, 0x49, 0xa9, 0x66, 0x80 | writingApp.length]), writingApp);

  const tagNameBytes = enc.encode('workflow');
  const tagName = concat(new Uint8Array([0x45, 0xa3, 0x80 | tagNameBytes.length]), tagNameBytes);
  const tagStrBytes = enc.encode('{"3":{"class_type":"KSampler"}}');
  const tagStr = concat(new Uint8Array([0x44, 0x87, 0x80 | tagStrBytes.length]), tagStrBytes);
  const simpleTagInner = concat(tagName, tagStr);
  const simpleTag = concat(new Uint8Array([0x67, 0xc8, 0x80 | simpleTagInner.length]), simpleTagInner);
  const tag = concat(new Uint8Array([0x73, 0x73, 0x80 | simpleTag.length]), simpleTag);
  const tags = concat(new Uint8Array([0x12, 0x54, 0xc3, 0x67, 0x80 | tag.length]), tag);

  const cluster = concat(new Uint8Array([0x1f, 0x43, 0xb6, 0x75, 0x84]), enc.encode('WEBM'));
  const segBody = concat(info, tags, cluster);
  const seg = concat(new Uint8Array([0x18, 0x53, 0x80, 0x67, 0x01, 0, 0, 0, 0, 0, 0, segBody.length]), segBody);
  return concat(ebmlHeader, seg);
}

test('scanMediaMetadata & stripMediaMetadata mendeteksi AI dan membersihkan lossless pada PNG, JPEG, WebP, GIF, MP4, WebM', async () => {
  // 1. PNG
  const png = buildAiPng();
  const pngScan = await scanMediaMetadata(png, { fileName: 'ai.png', mimeType: 'image/png' });
  assert.equal(pngScan.supported, true);
  assert.equal(pngScan.aiDetected, true);
  assert.ok(pngScan.detectedTools.includes('ComfyUI'));
  assert.ok(pngScan.detectedTools.includes('Stable Diffusion (A1111 / Forge / InvokeAI)'));
  assert.ok(pngScan.detectedTools.includes('C2PA / Content Credentials'));
  const pngClean = await stripMediaMetadata(png, { fileName: 'ai.png', mimeType: 'image/png' });
  assert.equal(pngClean.after.aiDetected, false);
  assert.equal(pngClean.after.totalEntries, 0);
  assert.ok(pngClean.removedCount >= 3);

  // 2. JPEG (ICC_PROFILE preserved!)
  const jpg = buildAiJpeg();
  const jpgScan = await scanMediaMetadata(jpg, { fileName: 'ai.jpg', mimeType: 'image/jpeg' });
  assert.equal(jpgScan.aiDetected, true);
  assert.ok(jpgScan.detectedTools.includes('OpenAI (Sora / DALL-E / ChatGPT)'));
  assert.ok(jpgScan.detectedTools.includes('Midjourney'));
  assert.ok(jpgScan.detectedTools.includes('C2PA / Content Credentials'));
  const jpgClean = await stripMediaMetadata(jpg, { fileName: 'ai.jpg', mimeType: 'image/jpeg' });
  assert.equal(jpgClean.after.aiDetected, false);
  assert.equal(jpgClean.after.totalEntries, 0);
  assert.ok(new TextDecoder().decode(jpgClean.cleanedBytes).includes('ICC_PROFILE'));

  // 3. WebP (VP8X flags cleared!)
  const webp = buildAiWebp();
  const webpScan = await scanMediaMetadata(webp, { fileName: 'ai.webp', mimeType: 'image/webp' });
  assert.equal(webpScan.aiDetected, true);
  assert.ok(webpScan.detectedTools.includes('Alibaba Cloud / Wan / Qwen AIGC'));
  const webpClean = await stripMediaMetadata(webp, { fileName: 'ai.webp', mimeType: 'image/webp' });
  assert.equal(webpClean.after.aiDetected, false);
  assert.equal(webpClean.after.totalEntries, 0);
  // VP8X flags byte at offset 12 (RIFF header) + 8 (VP8X hdr) = 20 should have bits 0x0c cleared
  assert.equal(webpClean.cleanedBytes[20] & 0x0c, 0);

  // 4. GIF (NETSCAPE2.0 looping preserved!)
  const gif = buildAiGif();
  const gifScan = await scanMediaMetadata(gif, { fileName: 'ai.gif', mimeType: 'image/gif' });
  assert.equal(gifScan.aiDetected, true);
  assert.ok(gifScan.detectedTools.includes('Runway'));
  const gifClean = await stripMediaMetadata(gif, { fileName: 'ai.gif', mimeType: 'image/gif' });
  assert.equal(gifClean.after.aiDetected, false);
  assert.equal(gifClean.after.totalEntries, 0);
  assert.ok(new TextDecoder().decode(gifClean.cleanedBytes).includes('NETSCAPE2.0'));

  // 5. MP4 (stco chunk offset updated to match new mdat start!)
  const { file: mp4, mdatPayloadOffsetBefore } = buildAiMp4();
  const mp4Scan = await scanMediaMetadata(mp4, { fileName: 'sora.mp4', mimeType: 'video/mp4' });
  assert.equal(mp4Scan.mediaKind, 'video');
  assert.equal(mp4Scan.aiDetected, true);
  assert.ok(mp4Scan.detectedTools.includes('OpenAI (Sora / DALL-E / ChatGPT)'));
  assert.ok(mp4Scan.detectedTools.includes('C2PA / Content Credentials'));
  assert.ok(mp4Scan.entries.some((e) => e.key === 'hdlr.name' && e.value.includes('OpenAI Sora Handler')));
  const mp4Clean = await stripMediaMetadata(mp4, { fileName: 'sora.mp4', mimeType: 'video/mp4' });
  assert.equal(mp4Clean.after.aiDetected, false);
  assert.equal(mp4Clean.after.totalEntries, 0);
  assert.equal(new TextDecoder().decode(mp4Clean.cleanedBytes).includes('OpenAI Sora Handler'), false);
  const mp4CleanParts = await stripMediaMetadata(mp4, { fileName: 'sora.mp4', mimeType: 'video/mp4', asParts: true });
  assert.equal(mp4CleanParts.after.aiDetected, false);
  assert.equal(mp4CleanParts.after.totalEntries, 0);
  assert.deepEqual(concat(...mp4CleanParts.cleanedChunks), mp4Clean.cleanedBytes);
  // Verify stco now points directly to 'VIDEO-DATA-PAYLOAD'
  const stcoIdx = Buffer.from(mp4Clean.cleanedBytes).indexOf('stco');
  const dv = new DataView(mp4Clean.cleanedBytes.buffer, mp4Clean.cleanedBytes.byteOffset);
  const newChunkOffset = dv.getUint32(stcoIdx + 12, false);
  assert.ok(newChunkOffset < mdatPayloadOffsetBefore);
  assert.equal(new TextDecoder().decode(mp4Clean.cleanedBytes.subarray(newChunkOffset, newChunkOffset + 18)), 'VIDEO-DATA-PAYLOAD');

  // 6. WebM (in-place Void scrubbing preserves Cluster offset!)
  const webm = buildAiWebm();
  const webmScan = await scanMediaMetadata(webm, { fileName: 'comfy.webm', mimeType: 'video/webm' });
  assert.equal(webmScan.mediaKind, 'video');
  assert.equal(webmScan.aiDetected, true);
  assert.ok(webmScan.detectedTools.includes('ComfyUI'));
  const webmClean = await stripMediaMetadata(webm, { fileName: 'comfy.webm', mimeType: 'video/webm' });
  assert.equal(webmClean.after.aiDetected, false);
  assert.equal(webmClean.after.totalEntries, 0);
  assert.equal(webmClean.cleanedBytes.length, webm.length);
  assert.equal(Buffer.from(webmClean.cleanedBytes).indexOf('WEBM'), Buffer.from(webm).indexOf('WEBM'));
  const webmCleanParts = await stripMediaMetadata(webm, { fileName: 'comfy.webm', mimeType: 'video/webm', asParts: true });
  assert.equal(webmCleanParts.after.aiDetected, false);
  assert.equal(webmCleanParts.after.totalEntries, 0);
  assert.deepEqual(concat(...webmCleanParts.cleanedChunks), webmClean.cleanedBytes);
});

function installMetadataFetchMock({ keyRows = [], modelRows = [], chatHandler = null } = {}) {
  const realFetch = globalThis.fetch;
  const chatCalls = [];
  globalThis.fetch = async (input, init = {}) => {
    const url = new URL(typeof input === 'string' ? input : input.url);
    if (url.href === 'https://supabase.example/auth/v1/user') {
      return Response.json({ id: USER_ID, email: 'creator@example.com', app_metadata: { role: 'user' } });
    }
    if (url.pathname === '/rest/v1/profiles') {
      return Response.json([{ id: USER_ID, email: 'creator@example.com', status: 'active' }]);
    }
    if (url.pathname === '/rest/v1/provider_api_keys') {
      return Response.json(keyRows);
    }
    if (url.pathname === '/rest/v1/provider_models') {
      return Response.json(modelRows);
    }
    if (/\/chat\/completions$/i.test(url.pathname) && chatHandler) {
      chatCalls.push({ url: url.href, body: JSON.parse(String(init.body || '{}')), headers: init.headers });
      return chatHandler({ url, init });
    }
    return realFetch(input, init);
  };
  return { chatCalls, restore: () => { globalThis.fetch = realFetch; } };
}

